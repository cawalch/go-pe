package testfixture

import (
	"encoding/binary"
	"fmt"
	"unicode/utf16"
)

// ResourceNodeSpec describes an IMAGE_RESOURCE_DIRECTORY node for synthetic
// fixtures. Reusing the same *ResourceNodeSpec pointer in multiple entries
// emits a single shared subtree node inside .rsrc (a DAG).
type ResourceNodeSpec struct {
	Characteristics uint32
	TimeDateStamp   uint32
	MajorVersion    uint16
	MinorVersion    uint16
	Entries         []ResourceEntrySpec
}

// ResourceEntrySpec describes one IMAGE_RESOURCE_DIRECTORY_ENTRY inside a node.
type ResourceEntrySpec struct {
	Named        bool
	Name         string
	RawNameUnits []uint16
	ID           uint32
	Subdir       *ResourceNodeSpec
	Leaf         *ResourceLeafSpec
}

// ResourceLeafSpec describes one IMAGE_RESOURCE_DATA_ENTRY leaf.
type ResourceLeafSpec struct {
	Payload              []byte
	ExternalDataRVA      uint32
	HasCustomRVA         bool
	DataSectionOffset    uint32
	HasDataSectionOffset bool
	CustomSize           uint32
	HasCustomSize        bool
	CodePage             uint32
	Reserved             uint32
}

// ResourceDirOffset returns the byte offset of DataDirectory[2] (Resource) in
// a PE image generated by Minimal.
func ResourceDirOffset(is64 bool) int {
	if is64 {
		return 280
	}
	return 264
}

// ResourceSectionOffset returns the byte offset of section index in a PE image
// generated by Minimal.
func ResourceSectionOffset(is64 bool, index int) int {
	base := 376
	if is64 {
		base = 392
	}
	return base + index*40
}

// Resources builds a single-section PE image containing the resource graph
// rooted at root in .rsrc at RVA 0x1000 (file offset 512).
func Resources(is64 bool, root *ResourceNodeSpec) []byte {
	return ResourcesWithDataSection(is64, root, nil)
}

// ResourcesWithDataSection builds a PE image with .rsrc at RVA 0x1000 and, when
// extraData is non-empty, a second section .data right after .rsrc so leaves
// can reference cross-section payloads via ExternalDataRVA. It returns the
// image bytes. Use CrossSectionRVA to compute RVAs inside extraData when
// calling ResourcesWithDataSection, or inspect section[1].VirtualAddress.
func ResourcesWithDataSection(is64 bool, root *ResourceNodeSpec, extraData []byte) []byte {
	sections := 1
	if len(extraData) > 0 {
		sections = 2
	}
	data := Minimal(is64, sections)
	const headerEnd = 512
	const rsrcRVA = uint32(0x1000)

	var rsrc []byte
	nodeOffsets := make(map[*ResourceNodeSpec]uint32)
	type pendingEntry struct {
		entryOff int
		entry    ResourceEntrySpec
	}
	var queue []*ResourceNodeSpec
	var namedPendings []pendingEntry
	var leafPendings []pendingEntry

	var allocNode func(n *ResourceNodeSpec) uint32
	allocNode = func(n *ResourceNodeSpec) uint32 {
		if off, ok := nodeOffsets[n]; ok {
			return off
		}
		off := uint32(len(rsrc))
		nodeOffsets[n] = off
		size := 16 + len(n.Entries)*8
		rsrc = append(rsrc, make([]byte, size)...)
		binary.LittleEndian.PutUint32(rsrc[off:], n.Characteristics)
		binary.LittleEndian.PutUint32(rsrc[off+4:], n.TimeDateStamp)
		binary.LittleEndian.PutUint16(rsrc[off+8:], n.MajorVersion)
		binary.LittleEndian.PutUint16(rsrc[off+10:], n.MinorVersion)
		var namedCount, idCount uint16
		for _, e := range n.Entries {
			if e.Named {
				namedCount++
			} else {
				idCount++
			}
		}
		binary.LittleEndian.PutUint16(rsrc[off+12:], namedCount)
		binary.LittleEndian.PutUint16(rsrc[off+14:], idCount)
		queue = append(queue, n)
		return off
	}

	allocNode(root)
	for qi := 0; qi < len(queue); qi++ {
		n := queue[qi]
		base := int(nodeOffsets[n])
		for i, e := range n.Entries {
			eOff := base + 16 + i*8
			if e.Named {
				namedPendings = append(namedPendings, pendingEntry{entryOff: eOff, entry: e})
			} else {
				binary.LittleEndian.PutUint32(rsrc[eOff:], e.ID)
			}
			if e.Subdir != nil {
				childOff := allocNode(e.Subdir)
				binary.LittleEndian.PutUint32(rsrc[eOff+4:], 0x80000000|childOff)
			} else {
				leafPendings = append(leafPendings, pendingEntry{entryOff: eOff, entry: e})
			}
		}
	}

	// Emit UTF-16LE name strings.
	for _, pe := range namedPendings {
		units := pe.entry.RawNameUnits
		if units == nil {
			units = utf16.Encode([]rune(pe.entry.Name))
		}
		strOff := uint32(len(rsrc))
		rsrc = append(rsrc, make([]byte, 2+len(units)*2)...)
		binary.LittleEndian.PutUint16(rsrc[strOff:], uint16(len(units)))
		for i, u := range units {
			binary.LittleEndian.PutUint16(rsrc[int(strOff)+2+i*2:], u)
		}
		binary.LittleEndian.PutUint32(rsrc[pe.entryOff:], 0x80000000|strOff)
	}

	// Reserve aligned .rsrc RVA first, emit DATA_ENTRY payloads, then patch
	// DataSectionOffset leaves once dataRVA is known.
	dataEntryOffs := make([]uint32, len(leafPendings))
	for i, lp := range leafPendings {
		deOff := uint32(len(rsrc))
		dataEntryOffs[i] = deOff
		rsrc = append(rsrc, make([]byte, 16)...)
		binary.LittleEndian.PutUint32(rsrc[lp.entryOff+4:], deOff)
	}
	var dataSectionLeaves []int
	for i, lp := range leafPendings {
		leaf := lp.entry.Leaf
		if leaf == nil {
			leaf = &ResourceLeafSpec{}
		}
		deOff := int(dataEntryOffs[i])
		var dataRVA uint32
		if leaf.HasCustomRVA {
			dataRVA = leaf.ExternalDataRVA
		} else if leaf.HasDataSectionOffset {
			dataSectionLeaves = append(dataSectionLeaves, i)
		} else {
			payloadOff := len(rsrc)
			rsrc = append(rsrc, leaf.Payload...)
			dataRVA = rsrcRVA + uint32(payloadOff)
		}
		size := uint32(len(leaf.Payload))
		if leaf.HasCustomSize {
			size = leaf.CustomSize
		}
		binary.LittleEndian.PutUint32(rsrc[deOff:], dataRVA)
		binary.LittleEndian.PutUint32(rsrc[deOff+4:], size)
		binary.LittleEndian.PutUint32(rsrc[deOff+8:], leaf.CodePage)
		binary.LittleEndian.PutUint32(rsrc[deOff+12:], leaf.Reserved)
	}

	rsrcDirSize := uint32(len(rsrc))
	rsrcPadded := (len(rsrc) + 511) &^ 511
	if rsrcPadded == 0 {
		rsrcPadded = 512
	}
	if len(rsrc) < rsrcPadded {
		rsrc = append(rsrc, make([]byte, rsrcPadded-len(rsrc))...)
	}

	dataRVA := (rsrcRVA + uint32(len(rsrc)) + 0xfff) &^ 0xfff
	for _, i := range dataSectionLeaves {
		deOff := int(dataEntryOffs[i])
		leaf := leafPendings[i].entry.Leaf
		binary.LittleEndian.PutUint32(rsrc[deOff:], dataRVA+leaf.DataSectionOffset)
	}

	out := append(data[:headerEnd], rsrc...)
	sec0 := ResourceSectionOffset(is64, 0)
	copy(out[sec0:sec0+8], ".rsrc\x00\x00\x00")
	binary.LittleEndian.PutUint32(out[sec0+8:], rsrcDirSize)
	binary.LittleEndian.PutUint32(out[sec0+12:], rsrcRVA)
	binary.LittleEndian.PutUint32(out[sec0+16:], uint32(len(rsrc)))
	binary.LittleEndian.PutUint32(out[sec0+20:], headerEnd)
	binary.LittleEndian.PutUint32(out[sec0+36:], 0x40000040)

	dirOff := ResourceDirOffset(is64)
	binary.LittleEndian.PutUint32(out[dirOff:], rsrcRVA)
	binary.LittleEndian.PutUint32(out[dirOff+4:], rsrcDirSize)

	optSizeOff := 152 + 56
	imageSize := ((rsrcRVA + uint32(len(rsrc)) + 0xfff) &^ 0xfff)

	if len(extraData) > 0 {
		dataPadded := (len(extraData) + 511) &^ 511
		dataOff := len(out)
		out = append(out, extraData...)
		if len(extraData) < dataPadded {
			out = append(out, make([]byte, dataPadded-len(extraData))...)
		}
		sec1 := ResourceSectionOffset(is64, 1)
		copy(out[sec1:sec1+8], ".data\x00\x00\x00")
		binary.LittleEndian.PutUint32(out[sec1+8:], uint32(len(extraData)))
		binary.LittleEndian.PutUint32(out[sec1+12:], dataRVA)
		binary.LittleEndian.PutUint32(out[sec1+16:], uint32(dataPadded))
		binary.LittleEndian.PutUint32(out[sec1+20:], uint32(dataOff))
		binary.LittleEndian.PutUint32(out[sec1+36:], 0xc0000040)
		imageSize = (dataRVA + uint32(dataPadded) + 0xfff) &^ 0xfff
	}

	binary.LittleEndian.PutUint32(out[optSizeOff:], imageSize)
	return out
}

// ResourcesSimple builds a single-section image with a standard 3-level
// (Type=10, ID=1..leaves, Language=1033) resource tree for benchmarks and
// differential tests.
func ResourcesSimple(is64 bool, leaves int) []byte {
	entries := make([]ResourceEntrySpec, leaves)
	for i := range leaves {
		payload := fmt.Appendf(nil, "payload-%05d", i)
		entries[i] = ResourceEntrySpec{
			ID: uint32(i + 1),
			Subdir: &ResourceNodeSpec{
				Entries: []ResourceEntrySpec{
					{
						ID: 1033,
						Leaf: &ResourceLeafSpec{
							Payload:  payload,
							CodePage: 1200,
						},
					},
				},
			},
		}
	}
	root := &ResourceNodeSpec{
		TimeDateStamp: 0x12345678,
		MajorVersion:  1,
		MinorVersion:  2,
		Entries: []ResourceEntrySpec{
			{
				ID: 10,
				Subdir: &ResourceNodeSpec{
					Entries: entries,
				},
			},
		},
	}
	return Resources(is64, root)
}
